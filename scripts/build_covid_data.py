"""Build js/data/covid-data.js from Our World in Data's COVID-19 dataset.

Usage:
    curl -L -o owid-covid-data.csv \
      https://raw.githubusercontent.com/owid/covid-19-data/master/public/data/owid-covid-data.csv
    python3 scripts/build_covid_data.py owid-covid-data.csv

Data: Our World in Data, https://github.com/owid/covid-19-data (CC BY 4.0).
"""

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

SNAPSHOT_DATE = "2022-12-31"  # end of year three; reporting thinned out after this
MIN_POPULATION = 1_000_000

# Output key -> OWID column. Values are the latest non-missing value on or
# before SNAPSHOT_DATE.
SNAPSHOT_COLUMNS = {
    "cases_pm": "total_cases_per_million",
    "deaths_pm": "total_deaths_per_million",
    "vax": "people_fully_vaccinated_per_hundred",
    "median_age": "median_age",
    "aged_65": "aged_65_older",
    "gdp": "gdp_per_capita",
    "beds": "hospital_beds_per_thousand",
    "life_exp": "life_expectancy",
    "hdi": "human_development_index",
    "population": "population",
}
REQUIRED = ["cases_pm", "deaths_pm", "vax", "median_age", "aged_65", "gdp", "beds", "life_exp", "hdi", "stringency"]

# Countries whose weekly epidemic curves are included for time-series lessons.
SERIES_COUNTRIES = ["USA", "GBR", "ITA", "DEU", "BRA", "IND", "ZAF", "JPN", "KOR"]
SERIES_START = "2020-03-02"
DAILY_COUNTRIES = ["DEU", "ITA", "USA", "IND"]
DAILY_RANGE = ("2020-03-01", "2021-02-28")

ROUND = {"cases_pm": 0, "deaths_pm": 1, "vax": 1, "median_age": 1, "aged_65": 1, "gdp": 0,
         "beds": 2, "life_exp": 1, "hdi": 3, "population": 0, "stringency": 1}


def main(csv_path: str) -> None:
    df = pd.read_csv(csv_path, parse_dates=["date"])
    df = df[df["continent"].notna()]  # drop aggregates such as "World" and "Europe"
    upto = df[df["date"] <= SNAPSHOT_DATE].sort_values("date")

    snap = upto.groupby("iso_code")[list(SNAPSHOT_COLUMNS.values())].last()
    snap.columns = list(SNAPSHOT_COLUMNS.keys())
    snap["stringency"] = upto[upto["date"] >= "2020-03-15"].groupby("iso_code")["stringency_index"].mean()
    meta = upto.groupby("iso_code")[["location", "continent"]].first()
    snap = snap.join(meta).dropna(subset=REQUIRED)
    snap = snap[snap["population"] >= MIN_POPULATION].sort_values("location")

    countries = []
    for iso, row in snap.iterrows():
        rec = {"iso": iso, "name": row["location"], "continent": row["continent"]}
        for key, digits in ROUND.items():
            v = float(row[key])
            rec[key] = int(round(v)) if digits == 0 else round(v, digits)
        countries.append(rec)

    # Weekly smoothed new cases / deaths per million (one value every 7 days).
    weekly = df[(df["iso_code"].isin(SERIES_COUNTRIES)) & (df["date"] >= SERIES_START) & (df["date"] <= SNAPSHOT_DATE)]
    dates = pd.date_range(SERIES_START, SNAPSHOT_DATE, freq="7D")
    series = {"dates": [d.strftime("%Y-%m-%d") for d in dates], "countries": []}
    for iso in SERIES_COUNTRIES:
        c = weekly[weekly["iso_code"] == iso].set_index("date").reindex(dates)
        series["countries"].append({
            "iso": iso,
            "name": str(df.loc[df["iso_code"] == iso, "location"].iloc[0]),
            "cases": [round(float(v), 1) for v in c["new_cases_smoothed_per_million"].fillna(0)],
            "deaths": [round(float(v), 2) for v in c["new_deaths_smoothed_per_million"].fillna(0)],
        })

    # Reported cases for the overfitting lesson. OWID's daily column carries a
    # weekly total on one reporting day (zeros in between), so keep the reports
    # as [day index, average per day over that week] pairs plus the daily trend.
    days = pd.date_range(*DAILY_RANGE, freq="D")
    daily = {"start": DAILY_RANGE[0], "days": len(days), "countries": []}
    for iso in DAILY_COUNTRIES:
        c = df[df["iso_code"] == iso].set_index("date").reindex(days)
        raw = c["new_cases_per_million"].fillna(0).to_numpy()
        daily["countries"].append({
            "iso": iso,
            "name": str(df.loc[df["iso_code"] == iso, "location"].iloc[0]),
            "reports": [[int(d), round(float(v) / 7, 1)] for d, v in enumerate(raw) if v > 0],
            "smooth": [round(float(v), 1) for v in c["new_cases_smoothed_per_million"].fillna(0)],
        })

    out = Path(__file__).resolve().parent.parent / "js" / "data" / "covid-data.js"
    out.parent.mkdir(parents=True, exist_ok=True)
    source = {
        "name": "Our World in Data – COVID-19 dataset",
        "url": "https://github.com/owid/covid-19-data",
        "license": "CC BY 4.0",
        "snapshot": SNAPSHOT_DATE,
        "notes": f"Countries with population ≥ {MIN_POPULATION:,} and no missing values in the fields used.",
    }
    body = (
        "// Generated by scripts/build_covid_data.py – do not edit by hand.\n"
        f"// Source: {source['name']} ({source['url']}), {source['license']}.\n"
        f"export const SOURCE = {json.dumps(source, ensure_ascii=False)};\n"
        f"export const COUNTRIES = {json.dumps(countries, ensure_ascii=False, separators=(',', ':'))};\n"
        f"export const SERIES = {json.dumps(series, separators=(',', ':'))};\n"
        f"export const DAILY = {json.dumps(daily, separators=(',', ':'))};\n"
    )
    out.write_text(body, encoding="utf-8")
    print(f"wrote {out} ({len(countries)} countries, {len(body) / 1024:.0f} KB)")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "owid-covid-data.csv")
